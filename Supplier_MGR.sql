-- PROCEDURE 1: RECORD_PAYMENT

CREATE OR REPLACE PROCEDURE RECORD_PAYMENT (
    P_INVOICE_ID IN NUMBER,
    P_PAYMENT_DATE IN DATE,
    P_AMOUNT_PAID IN NUMBER,
    P_PAYMENT_METHOD IN VARCHAR2,
    P_REFERENCE_NO IN VARCHAR2 DEFAULT NULL
) IS
    V_INVOICE_AMOUNT SUPPLIER_INVOICES.INVOICE_AMOUNT%TYPE;
    V_TOTAL_PAID NUMBER;
    V_NEW_STATUS VARCHAR2(20);
BEGIN
    SELECT INVOICE_AMOUNT INTO V_INVOICE_AMOUNT
    FROM SUPPLIER_INVOICES
    WHERE INVOICE_ID = P_INVOICE_ID;
    
    INSERT INTO PAYMENTS (INVOICE_ID, PAYMENT_DATE, AMOUNT_PAID, PAYMENT_METHOD, REFERENCE_NO)
    VALUES (P_INVOICE_ID, P_PAYMENT_DATE, P_AMOUNT_PAID, P_PAYMENT_METHOD, P_REFERENCE_NO);
    
    SELECT NVL(SUM(AMOUNT_PAID), 0) INTO V_TOTAL_PAID
    FROM PAYMENTS
    WHERE INVOICE_ID = P_INVOICE_ID;
    
    IF V_TOTAL_PAID = 0 THEN
        V_NEW_STATUS := 'UNPAID';
    ELSIF V_TOTAL_PAID < V_INVOICE_AMOUNT THEN
        V_NEW_STATUS := 'PARTIAL';
    ELSE
        V_NEW_STATUS := 'PAID';
    END IF;
    
    UPDATE SUPPLIER_INVOICES SET STATUS = V_NEW_STATUS
    WHERE INVOICE_ID = P_INVOICE_ID;
    
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Payment recorded. Invoice status: ' || V_NEW_STATUS);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Error: Invoice not found');
        ROLLBACK;
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Error: ' || SQLERRM);
        ROLLBACK;
END RECORD_PAYMENT;
/


-- PROCEDURE 2: GET_SUPPLIER_OUTSTANDING

CREATE OR REPLACE PROCEDURE GET_SUPPLIER_OUTSTANDING (
    P_SUPPLIER_ID IN NUMBER DEFAULT NULL
) IS
    CURSOR SUPPLIER_CURSOR IS
        SELECT S.SUPPLIER_NAME,
               NVL(SUM(SI.INVOICE_AMOUNT), 0) AS TOTAL_INVOICED,
               NVL(SUM(P.AMOUNT_PAID), 0) AS TOTAL_PAID,
               NVL(SUM(SI.INVOICE_AMOUNT), 0) - NVL(SUM(P.AMOUNT_PAID), 0) AS OUTSTANDING
        FROM SUPPLIERS S
        LEFT JOIN SUPPLIER_INVOICES SI ON S.SUPPLIER_ID = SI.SUPPLIER_ID
        LEFT JOIN PAYMENTS P ON SI.INVOICE_ID = P.INVOICE_ID
        WHERE (P_SUPPLIER_ID IS NULL OR S.SUPPLIER_ID = P_SUPPLIER_ID)
        GROUP BY S.SUPPLIER_NAME
        HAVING NVL(SUM(SI.INVOICE_AMOUNT), 0) - NVL(SUM(P.AMOUNT_PAID), 0) > 0
        ORDER BY OUTSTANDING DESC;
BEGIN
    DBMS_OUTPUT.PUT_LINE('==================================================');
    DBMS_OUTPUT.PUT_LINE('OUTSTANDING SUPPLIER BALANCES');
    DBMS_OUTPUT.PUT_LINE('==================================================');
    DBMS_OUTPUT.PUT_LINE(RPAD('Supplier Name', 30) || RPAD('Invoiced', 15) || RPAD('Paid', 15) || RPAD('Balance', 15));
    DBMS_OUTPUT.PUT_LINE('--------------------------------------------------');
    
    FOR REC IN SUPPLIER_CURSOR LOOP
        DBMS_OUTPUT.PUT_LINE(
            RPAD(SUBSTR(REC.SUPPLIER_NAME, 1, 28), 30) ||
            RPAD(TO_CHAR(REC.TOTAL_INVOICED, '999,999,999'), 15) ||
            RPAD(TO_CHAR(REC.TOTAL_PAID, '999,999,999'), 15) ||
            RPAD(TO_CHAR(REC.OUTSTANDING, '999,999,999'), 15)
        );
    END LOOP;
    
    DBMS_OUTPUT.PUT_LINE('==================================================');
END GET_SUPPLIER_OUTSTANDING;
/

-- TRIGGER 1: CHECK_PAYMENT_AMOUNT

CREATE OR REPLACE TRIGGER CHECK_PAYMENT_AMOUNT
    BEFORE INSERT OR UPDATE ON PAYMENTS
    FOR EACH ROW
DECLARE
    V_INVOICE_AMOUNT SUPPLIER_INVOICES.INVOICE_AMOUNT%TYPE;
    V_TOTAL_PAID NUMBER;
BEGIN
    SELECT INVOICE_AMOUNT INTO V_INVOICE_AMOUNT
    FROM SUPPLIER_INVOICES
    WHERE INVOICE_ID = :NEW.INVOICE_ID;
    
    SELECT NVL(SUM(AMOUNT_PAID), 0) + :NEW.AMOUNT_PAID INTO V_TOTAL_PAID
    FROM PAYMENTS
    WHERE INVOICE_ID = :NEW.INVOICE_ID;
    
    IF V_TOTAL_PAID > V_INVOICE_AMOUNT THEN
        RAISE_APPLICATION_ERROR(-20001, 
            'Payment cannot exceed invoice amount. Invoice: ' || TO_CHAR(V_INVOICE_AMOUNT) ||
            ', Total with this payment: ' || TO_CHAR(V_TOTAL_PAID));
    END IF;
END CHECK_PAYMENT_AMOUNT;
/


-- TRIGGER 2: UPDATE_INVOICE_STATUS_AFTER_PAYMENT

CREATE OR REPLACE TRIGGER UPDATE_INVOICE_STATUS_AFTER_PAYMENT
    AFTER INSERT OR UPDATE ON PAYMENTS
    FOR EACH ROW
DECLARE
    V_INVOICE_AMOUNT SUPPLIER_INVOICES.INVOICE_AMOUNT%TYPE;
    V_TOTAL_PAID NUMBER;
    V_NEW_STATUS VARCHAR2(20);
BEGIN
    SELECT INVOICE_AMOUNT INTO V_INVOICE_AMOUNT
    FROM SUPPLIER_INVOICES
    WHERE INVOICE_ID = :NEW.INVOICE_ID;
    
    SELECT NVL(SUM(AMOUNT_PAID), 0) INTO V_TOTAL_PAID
    FROM PAYMENTS
    WHERE INVOICE_ID = :NEW.INVOICE_ID;
    
    IF V_TOTAL_PAID = 0 THEN
        V_NEW_STATUS := 'UNPAID';
    ELSIF V_TOTAL_PAID < V_INVOICE_AMOUNT THEN
        V_NEW_STATUS := 'PARTIAL';
    ELSE
        V_NEW_STATUS := 'PAID';
    END IF;
    
    UPDATE SUPPLIER_INVOICES
    SET STATUS = V_NEW_STATUS
    WHERE INVOICE_ID = :NEW.INVOICE_ID;
    
    DBMS_OUTPUT.PUT_LINE('Invoice ' || :NEW.INVOICE_ID || ' status: ' || V_NEW_STATUS);
END UPDATE_INVOICE_STATUS_AFTER_PAYMENT;
/


-- TRIGGER 3: LOG_SUPPLIER_CHANGES (Audit)

CREATE OR REPLACE TRIGGER LOG_SUPPLIER_CHANGES
    AFTER INSERT OR UPDATE OR DELETE ON SUPPLIERS
    FOR EACH ROW
DECLARE
    V_ACTION VARCHAR2(10);
    V_USER VARCHAR2(50);
BEGIN
    SELECT USER INTO V_USER FROM DUAL;
    
    IF INSERTING THEN
        V_ACTION := 'INSERT';
        INSERT INTO SUPPLIER_AUDIT_LOG (SUPPLIER_ID, ACTION_TYPE, NEW_NAME, NEW_PHONE, CHANGED_BY)
        VALUES (:NEW.SUPPLIER_ID, V_ACTION, :NEW.SUPPLIER_NAME, :NEW.PHONE, V_USER);
    ELSIF UPDATING THEN
        V_ACTION := 'UPDATE';
        INSERT INTO SUPPLIER_AUDIT_LOG (SUPPLIER_ID, ACTION_TYPE, OLD_NAME, NEW_NAME, OLD_PHONE, NEW_PHONE, CHANGED_BY)
        VALUES (:OLD.SUPPLIER_ID, V_ACTION, :OLD.SUPPLIER_NAME, :NEW.SUPPLIER_NAME, :OLD.PHONE, :NEW.PHONE, V_USER);
    ELSIF DELETING THEN
        V_ACTION := 'DELETE';
        INSERT INTO SUPPLIER_AUDIT_LOG (SUPPLIER_ID, ACTION_TYPE, OLD_NAME, OLD_PHONE, CHANGED_BY)
        VALUES (:OLD.SUPPLIER_ID, V_ACTION, :OLD.SUPPLIER_NAME, :OLD.PHONE, V_USER);
    END IF;
    
    COMMIT;
END LOG_SUPPLIER_CHANGES;
